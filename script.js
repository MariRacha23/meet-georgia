function changeLanguage(lang) {
  const elements = document.querySelectorAll(".translate");
  elements.forEach((element) => {
    const key = element.getAttribute("data-key");
    if (translations[lang] && translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });
}

document.querySelectorAll(".lang-option").forEach((option) => {
  option.addEventListener("click", function () {
    const selectedLang = this.getAttribute("data-lang");
    changeLanguage(selectedLang);

    const flagSrc = this.querySelector("img").getAttribute("src");
    document.querySelector(".selected-lang img").setAttribute("src", flagSrc);
  });
});

const langPicker = document.querySelector(".lang-picker");
const langOptions = document.querySelector(".lang-options");
const selectedLangImg = document.querySelector(".selected-lang img");

if (langPicker) {
  langPicker.addEventListener("click", () => {
    langOptions.classList.toggle("show");
  });
}

document.querySelectorAll(".lang-option").forEach((option) => {
  option.addEventListener("click", (e) => {
    const lang = option.getAttribute("data-lang");
    selectedLangImg.src = option.querySelector("img").src;

    changeLanguage(lang);
    updateCardsLanguage(lang);
  });
});

window.addEventListener("click", (e) => {
  if (langPicker && !langPicker.contains(e.target)) {
    langOptions.classList.remove("show");
  }
});

